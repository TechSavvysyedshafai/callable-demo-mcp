from common import *
def dna(n=16,w=7.0,col=BLUE):
    xs=[ -w/2+i*w/(n-1) for i in range(n)]
    top=Line(LEFT*w/2+UP*0.35,RIGHT*w/2+UP*0.35,color=col,stroke_width=5); bot=Line(LEFT*w/2+DOWN*0.35,RIGHT*w/2+DOWN*0.35,color=col,stroke_width=5)
    rungs=VGroup(*[Line(UP*0.35+RIGHT*x,DOWN*0.35+RIGHT*x,color=MUTE,stroke_width=3) for x in xs])
    return VGroup(top,bot,rungs)
class CrisprPaper(Paper):
    def construct(self):
        # 0 title
        t=VGroup(Text("The paper that made",font_size=48,color=INK,weight=BOLD),Text("gene editing easy",font_size=48,color=GOLD,weight=BOLD)).arrange(DOWN,buff=0.25).move_to(UP*2.2)
        a=Text("Jinek, Chylinski, Fonfara, Hauer,\nDoudna & Charpentier",font_size=26,color=MUTE,line_spacing=0.9).next_to(t,DOWN,buff=0.5)
        j=Text("Science, 2012",font_size=28,color=MUTE).next_to(a,DOWN,buff=0.25)
        self.play(Write(t),run_time=1.5); self.play(FadeIn(a),FadeIn(j))
        self.cap("In 2012, one short paper showed how a bacterial defence system could become a tool to edit any gene.",6)
        self.clear_stage()
        # 1 bacteria keep virus mugshots
        h=self.heading("Bacteria fight viruses too")
        cell=Ellipse(width=7.4,height=4.2,color=GREEN,stroke_width=4).move_to(UP*2.4)
        phage=VGroup(RegularPolygon(6,color=RED).scale(0.45),Line(ORIGIN,DOWN*0.8,color=RED)).arrange(DOWN,buff=0).move_to(UP*5.0+RIGHT*1.5)
        self.play(Create(cell)); self.play(FadeIn(phage,shift=DOWN*0.3))
        vdna=Line(LEFT*0.8,RIGHT*0.8,color=RED,stroke_width=6).move_to(cell.get_center()+UP*0.6)
        self.play(phage.animate.move_to(cell.get_top()+UP*0.45+RIGHT*0.3),run_time=0.8); self.play(Create(vdna))
        self.cap("When a virus attacks, some bacteria survive and save a short piece of the virus DNA.",5)
        arr=VGroup()
        for i in range(9):
            if i%2==0: arr.add(Square(0.5,fill_color=MUTE,fill_opacity=0.8,stroke_width=0))
            else: arr.add(Rectangle(width=0.8,height=0.5,fill_color=[RED,GOLD,"#c792ea","#9cdcfe"][i//2],fill_opacity=0.9,stroke_width=0))
        arr.arrange(RIGHT,buff=0.04).move_to(cell.get_center()+DOWN*0.6)
        self.play(ReplacementTransform(vdna,arr[1])); self.play(LaggedStart(*[FadeIn(x) for k,x in enumerate(arr) if k!=1],lag_ratio=0.1))
        lab=Text("CRISPR: a 'mugshot album' of past viruses",font_size=26,color=INK).next_to(cell,DOWN,buff=0.4)
        self.play(FadeIn(lab))
        self.cap("They store these pieces in a row in their own DNA. This row is called CRISPR. It works like a mugshot album.",6)
        self.clear_stage()
        # 2 two RNAs + Cas9
        h=self.heading("Two RNAs guide one protein")
        cas=Ellipse(width=4.2,height=3.0,fill_color="#3a4766",fill_opacity=1,stroke_color=INK,stroke_width=2).move_to(UP*2.0)
        cl=Text("Cas9",font_size=40,color=INK,weight=BOLD).move_to(cas.get_center()+UP*0.7)
        cr=Line(LEFT*1.5,RIGHT*1.5,color=GOLD,stroke_width=8).move_to(UP*5.0+LEFT*0.3)
        crl=Text("crRNA: copy of a mugshot",font_size=24,color=GOLD).next_to(cr,UP,buff=0.15)
        tr=VMobject(color=GREEN,stroke_width=8).set_points_smoothly([RIGHT*0.2+UP*4.6,RIGHT*1.2+UP*4.7,RIGHT*1.6+UP*4.3,RIGHT*1.0+UP*4.0]).shift(LEFT*0.3)
        trl=Text("tracrRNA: the helper",font_size=24,color=GREEN).next_to(cr,DOWN,buff=0.6)
        self.play(Create(cr),FadeIn(crl)); self.play(Create(tr),FadeIn(trl))
        self.cap("The paper showed that a copy of one mugshot, called crRNA, pairs up with a helper RNA, called tracrRNA.",6)
        self.play(FadeIn(cas),FadeIn(cl)); self.play(VGroup(cr,tr).animate.move_to(cas.get_center()+DOWN*0.3),FadeOut(crl),FadeOut(trl),run_time=1.2)
        self.cap("Together, the two RNAs load into a protein called Cas9 and tell it which DNA to look for.",5.5)
        self.clear_stage()
        # 3 search, PAM, cut
        h=self.heading("Find. Match. Cut.")
        d=dna(18,7.0).move_to(UP*1.0)
        seq="ATGCCTAGGTTTGGACTA"; letters=VGroup(*[Text(c,font_size=26,color=INK).move_to(d[2][i].get_top()+UP*0.3) for i,c in enumerate(seq)])
        self.play(Create(d),FadeIn(letters),run_time=1.2)
        cas=Ellipse(width=3.2,height=2.0,fill_color="#3a4766",fill_opacity=0.55,stroke_color=INK).move_to(d.get_left()+RIGHT*1.4+UP*1.0)
        self.play(FadeIn(cas)); self.play(cas.animate.shift(RIGHT*3.6),run_time=1.6)
        self.cap("Cas9 scans the DNA. It stops at a short signal, NGG, called the PAM, and checks the letters next to it.",6)
        pam=SurroundingRectangle(VGroup(*letters[11:14]),color=RED,buff=0.06)
        guide=SurroundingRectangle(VGroup(*letters[3:11]),color=GOLD,buff=0.06)
        self.play(Create(pam)); self.play(Create(guide))
        self.cap("If the guide RNA matches the DNA (about 20 letters in real life), Cas9 cuts.",4.5)
        cutx=(d[2][7].get_center()+d[2][8].get_center())/2
        hnh=Text("HNH cuts one strand",font_size=32,color=GOLD).move_to(DOWN*1.5); ruv=Text("RuvC cuts the other strand",font_size=32,color=GREEN).move_to(DOWN*2.3)
        cutnote=Text("cut: 3 letters before the PAM",font_size=28,color=MUTE).move_to(DOWN*3.1)
        s1=Line(cutx+UP*0.6,cutx+UP*0.1,color=GOLD,stroke_width=6); s2=Line(cutx+DOWN*0.6,cutx+DOWN*0.1,color=GREEN,stroke_width=6)
        self.play(Create(s1),FadeIn(hnh)); self.play(Create(s2),FadeIn(ruv)); self.play(FadeIn(cutnote))
        y0=d[0].get_y(); y1=d[1].get_y(); xl=d[0].get_start()[0]; xr=d[0].get_end()[0]; cx=cutx[0]
        lt=Line([xl,y0,0],[cx,y0,0],color=BLUE,stroke_width=5); lb=Line([xl,y1,0],[cx,y1,0],color=BLUE,stroke_width=5)
        rt=Line([cx,y0,0],[xr,y0,0],color=BLUE,stroke_width=5); rb=Line([cx,y1,0],[xr,y1,0],color=BLUE,stroke_width=5)
        self.remove(d[0],d[1]); self.add(lt,lb,rt,rb)
        self.play(VGroup(lt,lb,*d[2][:8],*letters[:8]).animate.shift(LEFT*0.4),VGroup(rt,rb,*d[2][8:],*letters[8:],pam).animate.shift(RIGHT*0.4),FadeOut(s1),FadeOut(s2),FadeOut(guide),FadeOut(cas),run_time=1)
        self.cap("Two cutting parts of Cas9 each cut one strand, so both strands of the DNA break at that exact spot.",6)
        self.clear_stage()
        # 4 single guide RNA = programmable
        h=self.heading("One RNA. Any gene.")
        cr=Line(LEFT*1.6,RIGHT*0.2,color=GOLD,stroke_width=9).move_to(UP*3.2+LEFT*0.6); tr=Line(RIGHT*0.2,RIGHT*1.8,color=GREEN,stroke_width=9).move_to(UP*3.2+RIGHT*1.4)
        self.play(Create(cr),Create(tr))
        sg=VGroup(cr.copy(),tr.copy()).arrange(RIGHT,buff=0).move_to(UP*1.8)
        self.play(TransformFromCopy(VGroup(cr,tr),sg)); sgl=Text("single-guide RNA",font_size=30,color=INK).next_to(sg,DOWN,buff=0.25); self.play(FadeIn(sgl))
        self.cap("Then the big step: they joined the two RNAs into one. A single guide RNA worked just as well.",5.5)
        tg=VGroup(*[Text(s,font_size=30,color=c) for s,c in [("GACGTTACCAGT…",GOLD),("TTGACCATGCAA…",BLUE),("CCGATAGGTACT…",GREEN)]]).arrange(DOWN,buff=0.3).move_to(DOWN*0.8)
        self.play(LaggedStart(*[FadeIn(x,shift=LEFT*0.3) for x in tg],lag_ratio=0.3))
        self.cap("Change the guide letters and Cas9 goes to a different gene. Gene editing became programmable.",5.5)
        self.clear_stage()
        # 5 impact
        h=self.heading("What happened next")
        facts=VGroup(*[Text(s,font_size=36,color=c) for s,c in [("Labs everywhere began editing genes",INK),("2020: Nobel Prize in Chemistry",GOLD),("Doudna & Charpentier",MUTE),("2023: first approved CRISPR medicine",GREEN),("for sickle-cell disease",MUTE)]]).arrange(DOWN,buff=0.35).move_to(UP*1.6)
        if facts.width>8.4: facts.scale_to_fit_width(8.4)
        self.play(LaggedStart(*[FadeIn(x,shift=UP*0.2) for x in facts],lag_ratio=0.3),run_time=2.5)
        self.cap("Within eight years it won the Nobel Prize. In 2023, the first CRISPR medicine was approved, for sickle-cell disease.",6.5)
        self.cap("For Class 12: this links to the biotechnology chapters. Paper: Science 337, 816 (2012).",5)
        self.clear_stage(); self.play(FadeOut(self._cap)); self.wait(0.5)
